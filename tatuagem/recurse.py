def load_json_mappings():
    try:
        with open(os.path.join(BASE_DIR, "extension_to_lang.json"), "r", encoding="utf-8") as f:
            ext_to_lang = json.load(f)
        with open(os.path.join(BASE_DIR, "lang_to_block_syntax.json"), "r", encoding="utf-8") as f:
            lang_to_syntax = json.load(f)
        return ext_to_lang, lang_to_syntax
    except FileNotFoundError:
        print("Warning: JSON mapping files not found.")
        return {}, {}


EXT_TO_LANG, LANG_TO_SYNTAX = load_json_mappings()


def get_tattoo(phrase: str) -> str:
    """Renders `phrase` with the default settings."""
    return get_tattoo_string(phrase)


@lru_cache(maxsize=64)
def _compile_patterns(patterns: tuple) -> pathspec.PathSpec:
    return pathspec.GitIgnoreSpec.from_lines(patterns)


def should_ignore(filepath: str, target_path: str, patterns: List[str]) -> bool:
    """
    Check if a path should be ignored based on .tatignore patterns,
    using the same semantics as .gitignore ("*.log", "node_modules/", "build/**", ...).
    """
    if not patterns:
        return False
    try:
        rel_path = os.path.relpath(filepath, target_path)
    except ValueError:
        # If paths are on different drives (Windows), use absolute comparison
        rel_path = filepath
    rel_path = rel_path.replace(os.sep, "/")
    if os.path.isdir(filepath):
        rel_path += "/"
    return _compile_patterns(tuple(patterns)).match_file(rel_path)


def clean_syntax(s):
    if not s:
        return s
    if s.startswith("`") and s.endswith("`") and len(s) > 1:
        return s[1:-1]
    return s


def has_shebang(content: str) -> bool:
    """Check if the content starts with a shebang line."""
    if not content:
        return False
    first_line = content.split("\n", 1)[0]
    return first_line.startswith("#!")


def get_shebang(content: str) -> Optional[str]:
    """Extract the shebang line from content if present."""
    if has_shebang(content):
        return content.split("\n", 1)[0]
    return None


def load_tatignore_patterns(target_path: str) -> List[str]:
    """
    Load patterns from .tatignore file in the target directory.
    Returns a list of patterns to ignore.
    """
    tatignore_path = os.path.join(target_path, ".tatignore")
    patterns = []

    if os.path.exists(tatignore_path):
        try:
            with open(tatignore_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    # Skip empty lines and comments
                    if line and not line.startswith("#"):
                        patterns.append(line)
        except Exception as e:
            print(f"Warning: Could not read .tatignore file: {e}")

    return patterns


def is_tattoo_comment(text: str, min_lines: int = 5) -> bool:
    """
    Determine if a comment block is a tattoo (ASCII art) rather than human-readable documentation.

    A tattoo is characterized by:
    - High ratio of repetitive characters (like '0', '1', special symbols)
    - Lines with mostly the same character repeated
    - Very few actual words or readable text
    - Multiple consecutive lines with similar patterns

    Args:
        text: The comment text to analyze (without comment delimiters)
        min_lines: Minimum number of lines to consider it a potential tattoo

    Returns:
        True if the text appears to be a tattoo, False if it appears to be human-readable
    """
    if not text or not text.strip():
        return False

    lines = [line.strip() for line in text.split("\n") if line.strip()]

    # Need at least min_lines of content to be a tattoo
    if len(lines) < min_lines:
        return False

    # Count lines with high repetition of single characters
    repetitive_lines = 0
    total_chars = 0
    non_alnum_chars = 0

    for line in lines:
        if not line:
            continue

        # Count character frequencies in this line
        char_counts = {}
        for char in line:
            char_counts[char] = char_counts.get(char, 0) + 1

        # Check if any single character dominates the line (>70% of characters)
        max_char_count = max(char_counts.values()) if char_counts else 0
        if len(line) > 0 and max_char_count / len(line) > 0.7:
            repetitive_lines += 1

        # Count "tattoo-like" characters (non-alphabetic characters excluding spaces)
        for char in line:
            total_chars += 1
            if not char.isalpha() and not char.isspace():
                non_alnum_chars += 1

    # Calculate ratio of lines with high repetition
    repetitive_ratio = repetitive_lines / len(lines) if lines else 0

    # Calculate ratio of tattoo-like characters
    tattoo_char_ratio = non_alnum_chars / total_chars if total_chars > 0 else 0

    # Check if text contains common documentation words
    text_lower = text.lower()
    doc_words = [
        "the",
        "this",
        "that",
        "function",
        "class",
        "method",
        "return",
        "parameter",
        "arg",
        "description",
        "example",
        "note",
        "todo",
        "fixme",
        "bug",
        "author",
        "copyright",
        "license",
        "version",
        "see",
        "also",
        "raises",
        "warning",
    ]
    doc_word_count = sum(1 for word in doc_words if word in text_lower)

    # Decision criteria:
    # - If >30% of lines are repetitive OR >50% tattoo-like chars, likely a tattoo
    # - If <3 documentation words found, more likely to be ASCII art
    is_repetitive = repetitive_ratio > 0.3
    has_high_tattoo_chars = tattoo_char_ratio > 0.5
    lacks_doc_words = doc_word_count < 3

    # It's a tattoo if it's highly repetitive or has high tattoo chars AND lacks doc words
    return (is_repetitive or has_high_tattoo_chars) and lacks_doc_words


def extract_first_comment(content: str, start: str, end: str) -> Optional[str]:
    """
    Extract the content of the first comment block in the file.

    Args:
        content: The file content
        start: Comment start delimiter
        end: Comment end delimiter

    Returns:
        The text inside the first comment block, or None if not found
    """
    if not content.strip().startswith(start):
        return None

    try:
        # For line comments where start == end and it's short (like //, #)
        # vs block comments where start == end but it's long (like """, ''')
        is_line_comment = (start == end) and len(start) <= 2

        if is_line_comment:
            # Line comments - extract consecutive commented lines
            lines = content.split("\n")
            comment_lines = []
            for line in lines:
                stripped = line.strip()
                if stripped.startswith(start):
                    # Remove the comment delimiter and add to list
                    comment_lines.append(line.replace(start, "", 1))
                elif comment_lines:
                    # Stop when we hit a non-comment line after starting
                    break
            return "\n".join(comment_lines)
        else:
            # Block comments
            # Split by start delimiter
            parts = content.split(start, 1)
            if len(parts) <= 1:
                return None

            # Get the part after start delimiter
            after_start = parts[1]

            # Split by end delimiter
            comment_parts = after_start.split(end, 1)
            if not comment_parts:
                return None

            # Return the comment content (without delimiters)
            comment_content = comment_parts[0]
            return comment_content.strip()
    except (IndexError, ValueError):
        return None


def _needs_raw_string(text: str) -> bool:
    """
    Check if tattoo text contains characters that require a raw string
    block comment in Python (single/double quotes or backslashes).
    """
    return "'" in text or '"' in text or "\\" in text


def _pick_python_delimiters(text: str) -> tuple:
    """
    Pick the best Python block comment delimiters for the given tattoo text.
    If the text contains problematic characters (' " \\), use raw strings.
    Returns (start, end) delimiter pair.
    """
    if not _needs_raw_string(text):
        return '"""', '"""'

    # Prefer r""" but if the text contains """, fall back to r'''
    if '"""' not in text:
        return 'r"""', '"""'
    elif "'''" not in text:
        return "r'''", "'''"
    else:
        # Extremely rare: text contains both """ and '''
        # Use r""" and escape the triple quotes in the text by splitting
        # This is a best-effort fallback
        return 'r"""', '"""'


PYTHON_TRIPLE_QUOTE_DELIMITERS = {'"""', "'''", 'r"""', "r'''"}


def comment_text(filepath, text) -> Optional[str]:
    """Return commented text based on file extension and language syntax."""
    ext = os.path.splitext(os.path.basename(filepath))[1].lower()
    lang = EXT_TO_LANG.get(ext)
    if not lang:
        return None

    syntax = LANG_TO_SYNTAX.get(lang)
    if not syntax:
        return None

    start = clean_syntax(syntax.get("start"))
    end = clean_syntax(syntax.get("end"))

    if not start or not end or start == "none" or end == "none":
        return None

    if start != end:
        # Block comment (e.g., /* */ or <!-- -->)
        return f"{start}\n{text}\n{end}"
    else:
        # Start == End
        if len(start) >= 3:
            # Likely block delimiter like """ or '''
            # Check if we need raw strings for Python-style triple-quote blocks
            if start in ('"""', "'''"):
                start, end = _pick_python_delimiters(text)
            return f"{start}\n{text}\n{end}"
        else:
            # Likely line comment
            lines = text.split("\n")
            # Remove empty last line from split if text ends with newline
            if lines and not lines[-1]:
                lines.pop()
            commented_lines = [f"{start} {line}" for line in lines]
            return "\n".join(commented_lines)


def _tattoo_file(filepath: str, tattoo: str, overwrite: bool) -> Optional[str]:
    """
    Returns the new content for `filepath` with `tattoo` applied,
    or None if the file should be left alone.
    """
    commented_tattoo = comment_text(filepath, tattoo)
    if not commented_tattoo:
        return None  # unknown language
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    # Avoid double tattooing: the first line of the tattoo is already in the file
    tattoo_lines = commented_tattoo.split("\n")
    if not overwrite and len(tattoo_lines) > 1 and tattoo_lines[1].strip() in content:
        print(f"Skipping {filepath} (already tattooed?)")
        return None

    ext = os.path.splitext(os.path.basename(filepath))[1].lower()
    syntax = LANG_TO_SYNTAX.get(EXT_TO_LANG.get(ext))
    start = clean_syntax(syntax.get("start"))
    end = clean_syntax(syntax.get("end"))

    # Preserve the shebang, if any
    shebang = get_shebang(content)
    if shebang:
        content_body = content.split("\n", 1)[1] if "\n" in content else ""
    else:
        content_body = content
    prefix = (shebang + "\n" if shebang else "") + commented_tattoo + "\n\n"

    # Check if body starts with an existing tattoo
    # (includes raw string variants for Python-style triple quotes)
    starters_to_check = [start] + ([f"r{start}"] if start in ('"""', "'''") else [])
    stripped_body = content_body.strip()
    detected_start = next((s for s in starters_to_check if stripped_body.startswith(s)), None)
    # The end delimiter is always the non-raw version
    detected_end = detected_start.lstrip("r") if detected_start else end

    first_comment = (
        extract_first_comment(content_body, detected_start, detected_end) if detected_start else None
    )
    if not (first_comment and is_tattoo_comment(first_comment)):
        print(f"Tattooed {filepath}")
        return prefix + content_body

    if not overwrite:
        print(f"Skipping {filepath} (already tattooed, use --overwrite to replace)")
        return None

    rest = content_body.split(detected_start, 1)[1].split(detected_end, 1)
    body_without_tattoo = rest[1].lstrip() if len(rest) > 1 else content_body
    print(f"Re-tattooed {filepath} (replaced existing tattoo)")
    return prefix + body_without_tattoo


def apply_tattoo_to_directory(target_path, tattoo, overwrite=False, dry_run=False) -> List[str]:
    """
    Tattoos every recognised source file under `target_path`.
    Returns the files that were (or, with dry_run, would be) changed.
    """
    changed: List[str] = []
    if not tattoo or not tattoo.strip():
        print("Error: Tattoo content is empty or contains only whitespace. Aborting.")
        return changed
    print(f"{'Checking' if dry_run else 'Tattooing into'} {target_path}...")

    ignore_patterns = load_tatignore_patterns(target_path)
    if ignore_patterns:
        print(f"Loaded {len(ignore_patterns)} ignore pattern(s) from .tatignore")

    for root, dirs, files in os.walk(target_path):
        # Skip hidden directories (.git, .venv, ...) and ignored ones without descending
        dirs[:] = sorted(
            d
            for d in dirs
            if not d.startswith(".")
            and not should_ignore(os.path.join(root, d), target_path, ignore_patterns)
        )
        for file in sorted(files):
            filepath = os.path.join(root, file)
            if file.startswith("."):
                continue
            if should_ignore(filepath, target_path, ignore_patterns):
                print(f"Skipping {filepath} (matched .tatignore)")
                continue
            try:
                new_content = _tattoo_file(filepath, tattoo, overwrite)
            except (UnicodeDecodeError, IsADirectoryError, PermissionError):
                continue  # binary or unreadable
            except Exception as e:
                print(f"Error processing {filepath}: {e}")
                continue
            if new_content is None:
                continue
            changed.append(filepath)
            if not dry_run:
                with open(filepath, "w", encoding="utf-8") as f:
                    f.write(new_content)
    return changed


def main():
    parser = argparse.ArgumentParser(description="Recurse directory and add tattoo comments")
    parser.add_argument("--text", required=True, help="Text to tattoo")
    parser.add_argument("--path", required=True, help="Path to recurse")
    args = parser.parse_args()

    target_path = os.path.expanduser(args.path)
    if not os.path.exists(target_path):
        print(f"Path not found: {target_path}")
        return
    apply_tattoo_to_directory(target_path, get_tattoo(args.text).strip())


if __name__ == "__main__":
    main()
