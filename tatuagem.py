from params import TEMPLATE_SIZE, Image, ImageDraw, ImageFont, BASE_DIR
from initi import get_font_png_path, init_and_create_templates
import argparse, os, subprocess, sys

MARGIN = 3  # top and bottom margin of text
KWARGS_LIST = {"text", "backsplash", "font", "pattern", "margin"}
SPACE_MARGIN = 4  # This defines what a space should be in the font, because the space file is a solid sheet
FONT_DEFAULT = "unicode-arial.ttf"
DEFAULT_TEXT_CHAR = "1"
DEFAULT_BACKSPLASH_CHAR = "0"


# 3. Analyze RGB of Templates -> Produce Text Mask
def yield_char_matrix(char: str, font: str = FONT_DEFAULT, **kwargs):
    new_dir = os.path.join(BASE_DIR, "fonts", font[:-4])
    fpp = get_font_png_path(char, new_dir)
    imat = Image.open(fpp).quantize().getdata()
    o = [[] for _ in range(imat.size[1])]
    # fmt: off
    for ix, h in enumerate(range(imat.size[1])):
        for w in range(imat.size[0]):
            if char == " " and (SPACE_MARGIN < w < TEMPLATE_SIZE - SPACE_MARGIN):
                continue
            if (
                not sum([o - imat.getpixel((0,0,)) for o in [imat.getpixel((w,i,)) for i in range(imat.size[1])]])
                and char != " "
            ):
                continue
            o[ix].append(
                kwargs['text']
                if imat.getpixel((w, h,)) - imat.getpixel((0, 0,))
                else kwargs['backsplash']
            )
        # fmt: on
    return o


def tatuar(mat, pattern=None, backsplash=None, margin=None):
    # prints a `matrix`
    pure_mat = list(
        filter(lambda x: x and not all(c == backsplash for c in "".join(x)), mat)
    )
    margin = int(margin)
    pure_mat = (
        (
            marg := [
                [backsplash * sum([len(x) for x in pure_mat[0]])] for _ in range(margin)
            ]
        )
        + pure_mat
        + marg
    )
    tatuagem = ""
    for text_list in pure_mat:
        out = "".join(text_list)
        if pattern:
            for i, c in enumerate(out):
                tatuagem += pattern[i % len(pattern)] if c == backsplash else c
        else:
            for i, c in enumerate(out):
                tatuagem += c
        tatuagem += "\n"
    return tatuagem


def expose(mat, pattern=None, backsplash=None, margin=None):
    # prints a `matrix`
    tatu = tatuar(mat, pattern=pattern, backsplash=backsplash, margin=margin)
    print(tatu)


def concat(cmat, amat, sep: str = ""):
    # concatenates character matrices
    if not len(cmat) == len(amat):
        raise ValueError("equal len required")

    x = [[] for _ in range(len(cmat))]
    for ix, ab in enumerate(zip(cmat, amat)):
        a, b = ab
        x[ix] = a + ([sep] if a and b else []) + b
    return x


def get_tattoo_string(frase: str, space_count: int = SPACE_MARGIN, **kwargs):
    # space_count, number of backsplash chars defining a 'space'
    j = []
    oxo = [[] for _ in range(TEMPLATE_SIZE)]
    for x in frase:
        cmat = yield_char_matrix(x, **kwargs)
        if not j:
            j = concat(oxo, cmat)
        else:
            j = concat(j, cmat, sep=(kwargs["backsplash"]) * space_count)
    return tatuar(
        j,
        pattern=kwargs["pattern"],
        backsplash=kwargs["backsplash"],
        margin=kwargs["margin"],
    )


def tatuagem(frase: str, space_count: int = SPACE_MARGIN, **kwargs):
    tatu = get_tattoo_string(frase, space_count, **kwargs)
    print(tatu)


def generate_ascii_art_from_prompt(prompt: str) -> str:
    """Generate ASCII art from a text prompt using Ollama."""
    try:
        result = subprocess.run(
            ["ollama", "run", "llama3", f"Generate ASCII art for: {prompt}. Only output the ASCII art, no explanations."],
            capture_output=True,
            text=True,
            timeout=60,
        )
        if result.returncode == 0:
            return result.stdout.strip()
        else:
            print(f"Error generating ASCII art: {result.stderr}")
            return None
    except subprocess.TimeoutExpired:
        print("Timeout: Ollama took too long to respond.")
        return None
    except FileNotFoundError:
        print("Error: 'ollama' command not found. Please install Ollama.")
        return None
    except Exception as e:
        print(f"Error: {e}")
        return None


def get_user_confirmation(prompt: str, valid_responses: dict) -> str:
    """Get user input with validation."""
    while True:
        response = input(f"{prompt} ").strip().lower()
        if response in valid_responses:
            return response
        print(f"Invalid input. Please choose from: {', '.join(valid_responses.keys())}")


def ollama_studio(prompt: str, **kwargs):
    """Interactive Ollama tattoo studio workflow."""
    print("\n=== Ollama Tattoo Studio ===\n")
    print(f"Generating ASCII art from prompt: '{prompt}'")
    
    # Step 1: Generate tattoo from prompt
    ascii_art = None
    while True:
        print("\nGenerating tattoo...")
        ascii_art = generate_ascii_art_from_prompt(prompt)
        
        if ascii_art is None:
            print("Failed to generate ASCII art.")
            retry = get_user_confirmation("Try again? (Y/n):", {"y": True, "n": False, "": True})
            if retry == "n":
                print("Exiting Ollama Studio.")
                sys.exit(0)
            continue
        
        print("\n" + "="*60)
        print("Generated Tattoo:")
        print("="*60)
        print(ascii_art)
        print("="*60 + "\n")
        
        proceed = get_user_confirmation("Proceed with this tattoo? (Y/n):", {"y": True, "n": False, "": True})
        if proceed in ["y", ""]:
            break
        print("Regenerating...")
    
    # Step 2: Ask for header/footer options
    print("\nWould you like to add headers or footers?")
    addon_choice = get_user_confirmation("Choose (h=header, f=footer, b=both, n=neither):", 
                                        {"h": "header", "f": "footer", "b": "both", "n": "neither"})
    
    header_text = None
    footer_text = None
    
    # Step 3: Handle header if requested
    if addon_choice in ["h", "b"]:
        while True:
            header_prompt = input("\nEnter header text: ").strip()
            if not header_prompt:
                print("Header cannot be empty.")
                continue
            
            header_tattoo = get_tattoo_string(header_prompt, **kwargs)
            print("\n" + "="*60)
            print("Header Preview:")
            print("="*60)
            print(header_tattoo)
            print("="*60 + "\n")
            
            proceed = get_user_confirmation("Proceed with this header? (Y/n):", {"y": True, "n": False, "": True})
            if proceed in ["y", ""]:
                header_text = header_tattoo
                break
            print("Let's redo the header...")
    
    # Step 4: Handle footer if requested
    if addon_choice in ["f", "b"]:
        while True:
            footer_prompt = input("\nEnter footer text: ").strip()
            if not footer_prompt:
                print("Footer cannot be empty.")
                continue
            
            footer_tattoo = get_tattoo_string(footer_prompt, **kwargs)
            print("\n" + "="*60)
            print("Footer Preview:")
            print("="*60)
            print(footer_tattoo)
            print("="*60 + "\n")
            
            proceed = get_user_confirmation("Proceed with this footer? (Y/n):", {"y": True, "n": False, "": True})
            if proceed in ["y", ""]:
                footer_text = footer_tattoo
                break
            print("Let's redo the footer...")
    
    # Final output
    print("\n" + "="*60)
    print("FINAL TATTOO")
    print("="*60 + "\n")
    
    if header_text:
        print(header_text)
    
    print(ascii_art)
    
    if footer_text:
        print(footer_text)
    
    print("="*60 + "\n")


def main():
    # Create the parser
    parser = argparse.ArgumentParser(description="Tatuagem")
    # text is the char for the printout
    parser.add_argument("--text", default=DEFAULT_TEXT_CHAR, help="Set the text")  # fmt: skip
    parser.add_argument("--backsplash", default=DEFAULT_BACKSPLASH_CHAR, help="Choose backsplash")  # fmt: skip
    parser.add_argument("--font", default=FONT_DEFAULT, metavar="FONT", help="Set the font")  # fmt: skip
    parser.add_argument("--pattern", default=None, metavar="PATTERN", help="Set the pattern for backsplash")  # fmt: skip
    parser.add_argument(
        "--margin", default=MARGIN, help="Margin top and bottom for text"
    )
    parser.add_argument("--recurse-path", help="Path to recurse and apply tattoo")
    parser.add_argument("--file", "-f", help="Read text from file")
    parser.add_argument("--ollama-studio", metavar="PROMPT", help="Interactive Ollama tattoo studio with AI-generated ASCII art")

    args, positional_args = parser.parse_known_args()
    if not os.path.exists(z := os.path.join(BASE_DIR, "fonts", args.font)):
        init_and_create_templates(args.font)
    
    # Handle Ollama Studio mode
    if args.ollama_studio:
        ollama_studio(args.ollama_studio, **{a: getattr(args, a) for a in KWARGS_LIST})
        return
    
    print(f"text: {args.text}")
    print(f"backsplash: {args.backsplash}")
    print(f"font: {args.font}")
    print(f"pattern: {args.pattern}")
    print(f"margin: {args.margin}")

    if args.file:
        with open(args.file, "r") as f:
            arg0_frase = f.read()
    elif positional_args:
        arg0_frase = positional_args[0]
    else:
        print("Error: No text provided. Use positional argument or --file.")
        exit(1)

    if args.recurse_path:
        from recurse import apply_tattoo_to_directory

        if not args.file:
            tattoo = get_tattoo_string(
                arg0_frase, **{a: getattr(args, a) for a in KWARGS_LIST}
            )
        else:
            tattoo = arg0_frase
        apply_tattoo_to_directory(args.recurse_path, tattoo)
    else:
        # prints to screen
        tatuagem(arg0_frase, **{a: getattr(args, a) for a in KWARGS_LIST})


if __name__ == "__main__":
    main()
