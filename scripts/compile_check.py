# Tattooed files must still compile: copy the corpus, tattoo it in place, and re-run
# each file's compiler/syntax checker. Only files that passed before tattooing count.

import argparse
import contextlib
import io
import os
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from tatuagem.recurse import apply_tattoo_to_directory, get_tattoo  # noqa: E402

CHECKERS = {
    ".py": [sys.executable, "-m", "py_compile"],
    ".c": ["cc", "-fsyntax-only"],
    ".cpp": ["c++", "-fsyntax-only"],
    ".js": ["node", "--check"],
    ".rb": ["ruby", "-c"],
    ".sh": ["bash", "-n"],
    ".pl": ["perl", "-c"],
    ".php": ["php", "-l"],
    ".lua": ["luac", "-p"],
    ".swift": ["swiftc", "-parse"],
    ".cob": ["cobc", "-fsyntax-only"],
    ".applescript": ["osacompile", "-o", "/dev/null"],
}


def check(path: str) -> bool:
    cmd = CHECKERS[os.path.splitext(path)[1]] + [os.path.basename(path)]
    try:
        r = subprocess.run(cmd, cwd=os.path.dirname(path), capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return r.returncode == 0


def main():
    parser = argparse.ArgumentParser(description="Check tattooed corpus files still compile.")
    parser.add_argument("--corpus", default=os.path.join(ROOT, "tests", "hello_worlds"))
    args = parser.parse_args()
    available = {e: c for e, c in CHECKERS.items() if shutil.which(c[0])}
    tattoos = {
        "rendered": get_tattoo("tatuagem"),
        "art": open(os.path.join(ROOT, "test_input.txt"), encoding="utf-8").read(),
    }
    pool = ThreadPoolExecutor(max_workers=(os.cpu_count() or 2) * 2)
    files = [
        os.path.relpath(os.path.join(r, f), args.corpus)
        for r, _, fs in os.walk(args.corpus)
        for f in fs
        if os.path.splitext(f)[1] in available
    ]
    # only files that compiled before tattooing count
    ok = pool.map(check, [os.path.join(args.corpus, f) for f in files])
    baseline = {f for f, passed in zip(files, ok, strict=True) if passed}
    failures = 0
    for name, tattoo in tattoos.items():
        with tempfile.TemporaryDirectory() as tmp:
            corpus = shutil.copytree(args.corpus, os.path.join(tmp, "corpus"))
            with contextlib.redirect_stdout(io.StringIO()):
                changed = apply_tattoo_to_directory(corpus, tattoo)
            todo = sorted(baseline & {os.path.relpath(f, corpus) for f in changed})
            results = pool.map(check, [os.path.join(corpus, f) for f in todo])
            broken = [f for f, passed in zip(todo, results, strict=True) if not passed]
            failures += len(broken)
            print(f"{name}: {len(todo)} tattooed files re-checked, {len(broken)} broken")
            for f in broken:
                print(f"  BROKEN {f}")
    print("checkers:", ", ".join(sorted(available)))
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
