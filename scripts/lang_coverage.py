# Language coverage: the share of languages in tests/hello_worlds that tatuagem can tattoo.
#
# A language counts as covered when at least one of its corpus files gets tattooed
# with a comment that is valid in *that* language (so extension clashes like .m for
# Objective-C vs MATLAB don't count). Files are also stress-tested with the repo's
# dogfood art (quotes, backslashes, `*`, `--`): tatuagem may skip them, but must
# never write a comment the art could break out of.

import argparse
import contextlib
import io
import json
import os
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from tatuagem.recurse import (  # noqa: E402
    LANG_TO_SYNTAX,
    _tattoo_file,
    comment_style,
    comment_text,
    get_tattoo,
    resolve_language,
)

SKIP_FILES = {"ovo.yaml"}
NO_TEXT = "no text files in corpus"
NO_COMMENTS = "language has no comments"


def _valid_in(style, lang: str) -> bool:
    """Is the comment style tatuagem chose also a comment in `lang`?"""
    syntax = LANG_TO_SYNTAX.get(lang) or {}
    if syntax.get("mixed"):
        return True  # a folder of several languages: each file is judged by its own
    if syntax.get("top_ok") is False:
        return False
    kind, start, end = style
    if kind == "line":
        return syntax.get("line") == start
    block = syntax.get("block") or {}
    # Python-style blocks may be written as r""" / ''' depending on the tattoo
    return (start.lstrip("r"), end) == (block.get("start"), block.get("end")) or (
        block.get("start") in ('"""', "'''") and start.lstrip("r") in ('"""', "'''")
    )


def _safe(commented: str, style, tattoo: str) -> bool:
    kind, start, end = style
    if kind == "block":
        return commented == f"{start}\n{tattoo}\n{end}" and end not in tattoo
    return all(line.startswith(start) for line in commented.split("\n"))


def _why_not(lang: str, files: list, tattoo: str) -> str:
    syntax = LANG_TO_SYNTAX.get(lang) or {}
    if not files:
        return NO_TEXT
    if syntax.get("no_comments"):
        return NO_COMMENTS + (f": {syntax['note']}" if syntax.get("note") else "")
    if not (syntax.get("block") or syntax.get("line") or syntax.get("mixed")):
        return "no safe comment syntax known" + (f": {syntax['note']}" if syntax.get("note") else "")
    if syntax.get("top_ok") is False:
        return "comments not allowed at top of file"
    resolved = {os.path.basename(f): resolve_language(f) for f in files}
    if not any(resolved.values()):
        exts = sorted({os.path.splitext(f)[1] or os.path.basename(f) for f in files})
        return f"unmapped extension(s): {', '.join(exts)}"
    clashes = {v for v in resolved.values() if v and v != lang}
    if clashes and not any(
        comment_style(f, tattoo) and _valid_in(comment_style(f, tattoo), lang) for f in files
    ):
        return f"extension maps to {', '.join(sorted(clashes))}"
    if not any(comment_style(f, tattoo) for f in files):
        return "no safe comment style for this tattoo"
    return "tattoo failed"


def measure(corpus: str) -> dict:
    tattoo = get_tattoo("tatuagem")
    art = open(os.path.join(ROOT, "test_input.txt"), encoding="utf-8").read()
    langs = sorted(d for d in os.listdir(corpus) if os.path.isdir(os.path.join(corpus, d)))
    covered, uncovered = [], {}
    with tempfile.TemporaryDirectory() as tmp:
        for lang in langs:
            files = []
            for root, dirs, names in os.walk(os.path.join(corpus, lang)):
                dirs[:] = [d for d in dirs if not d.startswith(".")]
                for name in names:
                    if name in SKIP_FILES or name.startswith("."):
                        continue
                    path = os.path.join(root, name)
                    try:
                        with open(path, encoding="utf-8") as f:
                            f.read()
                    except (UnicodeDecodeError, OSError):
                        continue  # binary
                    files.append(path)

            ok = False
            for path in files:
                copy = os.path.join(tmp, os.path.basename(path))
                # stress test: tatuagem may decline, but must never emit a breakable comment
                art_style = comment_style(path, art)
                if art_style:
                    assert _safe(comment_text(path, art), art_style, art), path
                style = comment_style(path, tattoo)
                if not style or not _valid_in(style, lang):
                    continue
                shutil.copyfile(path, copy)
                if _tattoo_file(copy, tattoo, overwrite=True):
                    ok = True
                    break
            if ok:
                covered.append(lang)
            else:
                uncovered[lang] = _why_not(lang, files, tattoo)

    # Languages that cannot hold a comment at all (or have no text in the corpus)
    # are listed but left out of the headline figure.
    impossible = [k for k, v in uncovered.items() if v.startswith((NO_TEXT, NO_COMMENTS))]
    eligible = len(langs) - len(impossible)
    return {
        "covered": len(covered),
        "eligible": eligible,
        "total": len(langs),
        "percent": round(100 * len(covered) / eligible, 1),
        "percent_of_all": round(100 * len(covered) / len(langs), 1),
        "uncovered": uncovered,
    }


def shields(label: str, pct: float, detail: str = "") -> dict:
    color = "brightgreen" if pct >= 90 else "green" if pct >= 75 else "yellow" if pct >= 50 else "red"
    return {
        "schemaVersion": 1,
        "label": label,
        "message": f"{pct:.1f}%" + (f" ({detail})" if detail else ""),
        "color": color,
    }


def markdown(result: dict) -> str:
    out = [
        f"## Language coverage: {result['percent']}% "
        f"({result['covered']}/{result['eligible']} languages that can hold a comment)",
        "",
        f"{result['percent_of_all']}% of all {result['total']} corpus folders; "
        "languages with no comments at all are listed below but not counted.",
        "",
        "| Language | Why not covered |",
        "|---|---|",
    ]
    out += [f"| {k} | {v} |" for k, v in sorted(result["uncovered"].items())]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(
        description="Measure how many corpus languages tatuagem can tattoo."
    )
    parser.add_argument("--corpus", default=os.path.join(ROOT, "tests", "hello_worlds"))
    parser.add_argument("--json", help="write the full result here")
    parser.add_argument("--badge", help="write a shields.io endpoint badge here")
    parser.add_argument("--summary", help="append a markdown report here")
    parser.add_argument("--min", type=float, default=0, help="exit 1 below this percent")
    args = parser.parse_args()

    with contextlib.redirect_stdout(io.StringIO()):  # silence per-file "Tattooed ..." lines
        result = measure(args.corpus)
    print(
        f"language coverage: {result['percent']}% ({result['covered']}/{result['eligible']}); "
        f"{result['percent_of_all']}% of all {result['total']} folders"
    )

    if args.json:
        with open(args.json, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=2, sort_keys=True)
    if args.badge:
        with open(args.badge, "w", encoding="utf-8") as f:
            json.dump(
                shields("languages", result["percent"], f"{result['covered']}/{result['eligible']}"), f
            )
    if args.summary:
        with open(args.summary, "a", encoding="utf-8") as f:
            f.write(markdown(result))
    if result["percent"] < args.min:
        print(f"below the required {args.min}%", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
